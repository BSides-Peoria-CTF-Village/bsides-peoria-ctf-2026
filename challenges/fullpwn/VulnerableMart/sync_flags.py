#!/usr/bin/env python3
"""Generate one scoring manifest per deployed flag; --check detects drift.

Vulnerable Mart deploys as a single shared docker-backend stack (see
stack.json). Only Staff Login (STAFF_FLAG) carries the `docker_image:
stack:vulnerablemart` launcher, so it's the one CTFd challenge with a
Start/Stop button; the other seven stages are plain `dynamic` scoring
entries that ride the same running environment.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STAGES = (
    ("01-staff-login", "Staff Login", "STAFF_FLAG", "Find your way into the staff area of Vulnerable Mart."),
    ("02-admin-panel", "Admin Panel", "ADMIN_FLAG", "Gain access to the shop's admin panel."),
    ("03-checkout", "Checkout", "CHECKOUT_FLAG", "Get a better deal at checkout."),
    ("04-maintenance-shell", "Maintenance Shell", "SHELL_FLAG", "Find the maintenance service and recover its flag."),
    ("05-seller-portal", "Seller Portal", "SELLER_FLAG", "Join the marketplace as a seller."),
    ("06-portal-admin", "Portal Admin", "PORTAL_ADMIN_FLAG", "Reach the seller portal's admin console."),
    ("07-user", "User", "USER_FLAG", "Get a foothold on the invoicing host and recover the user flag."),
    ("08-root", "Root", "ROOT_FLAG", "Take control of the invoicing host and recover the root flag."),
)


def manifests():
    values = {}
    for line in (ROOT / "flags.env").read_text().splitlines():
        if line.strip() and not line.lstrip().startswith("#"):
            key, value = line.split("=", 1)
            values[key] = value
    flags = [values[key] for _, _, key, _ in STAGES]

    # Cross-check against stack.json: the file docker-backend actually reads
    # to spawn the shared environment. If these drift apart, the challenge
    # description's promises (one shared stack, 90 minutes) would be a lie.
    spec = json.loads((ROOT / "stack.json").read_text())
    if spec.get("ttl_seconds") != 5400:
        raise ValueError("Vulnerable Mart must have a 90-minute lifetime (stack.json ttl_seconds=5400)")
    deployed = [key for service in spec.get("services", {}).values() for key in service.get("env", [])]
    if any(key not in values for key in deployed):
        raise ValueError("stack.json references an environment value missing from flags.env")
    flag_keys = {key for _, _, key, _ in STAGES}
    deployed_flag_keys = {key for key in deployed if key.endswith("_FLAG")}
    if deployed_flag_keys != flag_keys:
        raise ValueError("stack.json must deploy exactly the eight scored flags")
    if len([key for key in deployed if key in flag_keys]) != 8:
        raise ValueError("Each flag must be scoped to exactly one stack.json service")

    if len(set(flags)) != len(STAGES) or any(not flag.startswith("PIA{") or not flag.endswith("}") for flag in flags):
        raise ValueError("Expected eight unique PIA{...} flags in flags.env")

    for slug, title, key, description in STAGES:
        is_launcher = key == "STAFF_FLAG"
        type_lines = "type: docker\ndocker_image: stack:vulnerablemart\n" if is_launcher else "type: dynamic\n"
        yield ROOT / "challenges" / f"{slug}.yaml", (
            "# Generated by sync_flags.py from flags.env; edit the generator for metadata changes.\n"
            f"name: {json.dumps('Vulnerable Mart - ' + title)}\n"
            "category: fullpwn\n"
            + type_lines +
            "description: |\n"
            f"  {description}\n\n"
            "  Start your team's environment from **Vulnerable Mart - Staff Login**.\n"
            "  That single environment serves all eight flags and lasts 90 minutes.\n"
            "  Use the Shop, Maintenance, Seller Portal and SSH endpoints shown there.\n"
            "  Stop then Start there to reset the entire environment.\n"
            "  Submit the flag for this stage here.\n"
            "function: logarithmic\ninitial: 500\nminimum: 100\ndecay: 9\nstate: visible\n"
            f"flag: {json.dumps(values[key])}\n"
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = dict(manifests())
    extra = set((ROOT / "challenges").glob("*.yaml")) - set(expected)
    if extra:
        raise SystemExit(f"Unexpected scoring manifests: {sorted(str(p) for p in extra)}")
    for path, content in expected.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Scoring manifest out of sync: {path.name}; run sync_flags.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Wrote'} {len(expected)} separate Fullpwn scoring entries.")


if __name__ == "__main__":
    main()
