#!/usr/bin/env python3
"""Generate one scoring manifest per deployed flag; --check detects drift."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STAGES = (
    ("01-staff-login", "Staff Login", "STAFF_FLAG", "Find your way into the staff area of Vulnerable Mart."),
    ("02-admin-panel", "Admin Panel", "ADMIN_FLAG", "Gain access to the shop's admin panel."),
    ("03-checkout", "Checkout", "CHECKOUT_FLAG", "Get a better deal at checkout."),
    ("04-maintenance-shell", "Maintenance Shell", "SHELL_FLAG", "Find the maintenance service and recover its flag."),
    ("05-seller-portal", "Seller Portal", "SELLER_FLAG", "Join the marketplace as a seller."),
    ("06-portal-admin", "Portal Admin", "PORTAL_ADMIN_FLAG", "Reach the seller portal's admin console."),
    ("07-user", "User", "USER_FLAG", "Get a foothold on the invoicing host and recover the user flag."),
    ("08-root", "Root", "ROOT_FLAG", "Take control of the invoicing host and recover the root flag."),
)


def manifests():
    values = {}
    for line in (ROOT / "flags.env").read_text().splitlines():
        if line.strip() and not line.lstrip().startswith("#"):
            key, value = line.split("=", 1)
            values[key] = value
    flags = [values[key] for _, _, key, _ in STAGES]
    if len(set(flags)) != len(STAGES) or any(not flag.startswith("CTF{") or not flag.endswith("}") for flag in flags):
        raise ValueError("Expected eight unique CTF{...} flags in flags.env")
    for slug, title, key, description in STAGES:
        yield ROOT / "challenges" / f"{slug}.yaml", (
            "# Generated by sync_flags.py from flags.env; edit the generator for metadata changes.\n"
            f"name: {json.dumps('Vulnerable Mart - ' + title)}\n"
            "category: fullpwn\n"
            "type: dynamic\n"
            "description: |\n"
            f"  {description}\n\n"
            "  All eight Vulnerable Mart challenges share one environment. Use the host\n"
            "  supplied by the organizers; the shop starts on HTTP port 8888.\n"
            "  Submit the flag for this stage here.\n"
            "function: logarithmic\ninitial: 500\nminimum: 100\ndecay: 9\nstate: visible\n"
            f"flag: {json.dumps(values[key])}\n"
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = dict(manifests())
    extra = set((ROOT / "challenges").glob("*.yaml")) - set(expected)
    if extra:
        raise SystemExit(f"Unexpected scoring manifests: {sorted(str(p) for p in extra)}")
    for path, content in expected.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Scoring manifest out of sync: {path.name}; run sync_flags.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Wrote'} {len(expected)} separate Fullpwn scoring entries.")


if __name__ == "__main__":
    main()
