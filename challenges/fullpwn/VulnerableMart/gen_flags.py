#!/usr/bin/env python3
"""Generate a flags.env with randomized flags + secrets for a fresh deploy.

Usage:
    python gen_flags.py            # writes flags.env (refuses to overwrite)
    python gen_flags.py --force    # overwrite an existing flags.env

Each flag keeps a human-readable prefix describing the step it rewards, plus a
random suffix so flags differ per event and can't be shared between teams.
"""
import argparse
import base64
import hashlib
import os
import secrets
import string
import subprocess


def rand(n=8):
    alphabet = string.ascii_lowercase + string.digits
    return ''.join(secrets.choice(alphabet) for _ in range(n))


def sha512_crypt(password):
    """Return a $6$ (sha512-crypt) hash string for `password`.

    Tries the stdlib `crypt` module first (removed in Python 3.13), then falls
    back to `openssl passwd -6`. This is the value that lands in mysterioususer's
    /etc/shadow on the maintenance host.
    """
    salt = rand(16)
    try:
        import crypt  # noqa: WPS433  (optional, platform/version dependent)
        return crypt.crypt(password, f"$6${salt}$")
    except Exception:
        pass
    try:
        out = subprocess.run(
            ["openssl", "passwd", "-6", "-salt", salt, password],
            capture_output=True, text=True, check=True,
        )
        digest = out.stdout.strip()
        if digest.startswith("$6$"):
            return digest
    except Exception:
        pass
    raise SystemExit(
        "Could not compute a sha512-crypt hash: need either the Python `crypt` "
        "module or `openssl` on PATH."
    )


def registration_key(shadow_hash, admin_password):
    # MUST stay in sync with portal/reg.py:compute_registration_key().
    data = (shadow_hash + admin_password).encode()
    return hashlib.shake_256(data).hexdigest(64)  # 512-bit output


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--force', action='store_true', help='overwrite flags.env')
    parser.add_argument('--out', default='flags.env')
    args = parser.parse_args()

    if os.path.exists(args.out) and not args.force:
        raise SystemExit(f"{args.out} already exists; pass --force to overwrite.")

    admin_password = "superepicadminpassword-" + rand(26)

    # mysterioususer lives on the 50050 container; its /etc/shadow hash is half of
    # the portal registration key. Store the hash base64-encoded so the '$' chars
    # never reach an env file / shell sourcing.
    mysterious_password = "mystery-" + rand(20)
    mysterious_hash = sha512_crypt(mysterious_password)
    mysterious_hash_b64 = base64.b64encode(mysterious_hash.encode()).decode()

    reg_key = registration_key(mysterious_hash, admin_password)

    values = {
        # Web app secret (session signing).
        "SECRET_KEY": secrets.token_hex(24),
        "PORTAL_SECRET_KEY": secrets.token_hex(24),

        # Admin DB password recovered via SQLi + single-base64 decode.
        # Readable prefix so it's obviously a password once decoded, plus a
        # 26-char random alphanumeric tail so it's not brute-forceable. Stays
        # alphanumeric+hyphen -> safe for env files and shell sourcing.
        # (Staff creds are NOT here: they must be a literal in app.py so the LFI
        # step can actually reveal a working password.)
        "ADMIN_PASSWORD": admin_password,

        # mysterioususer (50050 container) + the precomputed portal reg key.
        "MYSTERIOUS_USER_PASSWORD": mysterious_password,
        "MYSTERIOUS_USER_HASH_B64": mysterious_hash_b64,
        "REGISTRATION_KEY": reg_key,

        # Capstone (portal container): jdoe SSH password leaked via the PDF LFI.
        "SSH_PASSWORD": "ssh-" + rand(20),

        # Submittable flags (one per step). Prefixes name the step; 24-char random
        # tail resists brute-forcing.
        "STAFF_FLAG":        f"PIA{{staff_login_success_{rand(24)}}}",
        "ADMIN_FLAG":        f"PIA{{4dm1n_v1ew_h34d3r_{rand(24)}}}",
        "CHECKOUT_FLAG":     f"PIA{{burp_param_tamp3ring_{rand(24)}}}",
        "SHELL_FLAG":        f"PIA{{cmd_1nj3ction_sh3ll_{rand(24)}}}",
        "SELLER_FLAG":       f"PIA{{s3ller_portal_r3g1st3r3d_{rand(24)}}}",
        "PORTAL_ADMIN_FLAG": f"PIA{{jwt_rs256_hs256_c0nfus10n_{rand(24)}}}",
        "USER_FLAG":         f"PIA{{pdf_lf1_t0_ssh_f00th0ld_{rand(24)}}}",
        "ROOT_FLAG":         f"PIA{{chef_g7f0b1n_r00t_pwn3d_{rand(24)}}}",
    }

    with open(args.out, 'w') as f:
        f.write("# Auto-generated by gen_flags.py. Do NOT commit this file.\n")
        for k, v in values.items():
            f.write(f"{k}={v}\n")

    os.chmod(args.out, 0o600)
    print(f"Wrote {args.out} with randomized flags and secrets.")
    print("Flags for the scoreboard:")
    for k in ("STAFF_FLAG", "ADMIN_FLAG", "CHECKOUT_FLAG", "SHELL_FLAG",
              "SELLER_FLAG", "PORTAL_ADMIN_FLAG", "USER_FLAG", "ROOT_FLAG"):
        print(f"  {k} = {values[k]}")
    print("Portal lock:")
    print(f"  mysterioususer password : {mysterious_password}")
    print(f"  REGISTRATION_KEY        : {reg_key}")


if __name__ == "__main__":
    main()
